def first_order(tau, target):
    return lambda t, y: ((target - y[0]) / tau,)


def test_rk4_matches_first_order_step_response():
    traj = sd.integrate(first_order(10.0, 2.0), (0.0,), 50, dt=1.0)
    err = max(abs(y[0] - sd.first_order_step_exact(i, 10.0, 2.0)) for i, y in enumerate(traj))
    assert err < 1e-6


def test_rk4_matches_two_stage_chain_and_bunching_pulse():
    """D follows a step with tau_d; Dc follows D with tau_c (both analytic); with D held constant,
    the Q-K pair with tau_q = tau_k = tau and adapt = 1 gives Q = dU (t/tau) exp(-t/tau)."""
    p = sd.Params(t0=0.0, d_max=0.8, tau_d=5.0, tau_c=12.0, tau_a=1e9, beta=0.0)
    traj = sd.simulate(p, 60, y0=(0.0, 0.0, 0.0, p.u0, 0.0, 0.0, 0.0))
    for t in (1, 7, 20, 60):
        d = 0.8 * (1 - math.exp(-t / 5.0))
        dc = 0.8 * (1 - (12.0 * math.exp(-t / 12.0) - 5.0 * math.exp(-t / 5.0)) / 7.0)
        assert traj[t][0] == pytest.approx(d, abs=1e-5)
        assert traj[t][1] == pytest.approx(dc, abs=1e-5)
    q = sd.Params(beta=0.15, tau_q=40.0, tau_k=40.0, adapt=1.0, tau_a=30.0, tau_u=1.0)
    d = 0.6
    du = 0.15 * d
    traj = sd.simulate(q, 200, target=lambda t: d, y0=(d, d, d, q.u0 + du, 0.0, 0.0, d))
    for t in (10, 40, 100, 200):
        assert traj[t][3] == pytest.approx(q.u0 + du, abs=1e-12)            # U stays put
        assert traj[t][4] == pytest.approx(du * t / 40.0 * math.exp(-t / 40.0), abs=1e-7)


def test_convergence_orders_of_rk4_and_euler():
    def error(method, dt):
        n = int(round(20.0 / dt))
        traj = sd.integrate(first_order(4.0, 1.0), (0.0,), n, dt=dt, method=method)
        return abs(traj[-1][0] - sd.first_order_step_exact(20.0, 4.0, 1.0))

    rk = error("rk4", 1.0) / error("rk4", 0.5)
    eu = error("euler", 1.0) / error("euler", 0.5)
    assert 12.0 < rk < 20.0          # fourth order: halving the step cuts the error ~16x
    assert 1.6 < eu < 2.4            # first order: ~2x


